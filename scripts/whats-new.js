// Writes the data behind the What's New page Fly opens after an upgrade.
//
// `release.js prepare` calls this with the pull requests going out, so the
// page is written by the release itself. Each pull request with a user-visible
// impact becomes an entry under its title. A pull request may add a
// `## What's New` section to its description to say more: plain lines become
// its description, `- ` lines its points, and a leading `### Heading` replaces
// the title. The section is optional, so a hand-opened pull request still only
// needs its impact label.
//
// Every release is kept, newest first, so someone skipping releases sees all
// of the ones they missed.
'use strict';
const fs = require('node:fs');
const path = require('node:path');

const DATA_FILE = path.join(__dirname, '..', 'chromium/overlay/fly/resources/whats_new/whats-new-releases.js');
const PREFIX = '// Generated by scripts/whats-new.js when a release is prepared. Do not edit by hand.\nwindow.FLY_RELEASES = ';
const SHOWN = ['major', 'minor', 'patch'];
const HEADING = /^##\s+what[’']?s\s+new\s*$/i;

// The `## What's New` section of a pull request description, or null.
function extractNote(body) {
    const lines = String(body || '').replace(/\r\n?/g, '\n').split('\n');
    const start = lines.findIndex(line => HEADING.test(line.trim()));
    if (start === -1) return null;
    const note = {title: null, text: [], points: []};
    let current = null;
    for (const raw of lines.slice(start + 1)) {
        const line = raw.trim();
        if (/^#{1,2}\s/.test(line)) break;
        if (/^<!--.*-->$/.test(line)) continue;
        if (/^###\s+/.test(line)) {
            if (!note.title && !note.text.length && !note.points.length) note.title = line.replace(/^###\s+/, '');
            current = null;
        } else if (/^[-*]\s+/.test(line)) {
            note.points.push(line.replace(/^[-*]\s+/, ''));
            current = 'points';
        } else if (!line) {
            current = null;
        } else if (current === 'points' && /^\s/.test(raw)) {
            note.points[note.points.length - 1] += ` ${line}`;
        } else if (current === 'text') {
            note.text[note.text.length - 1] += ` ${line}`;
        } else {
            note.text.push(line);
            current = 'text';
        }
    }
    return note.title || note.text.length || note.points.length ? note : null;
}

// The entry for one release: every change a user could notice, most important first.
function releaseEntry(version, date, pulls) {
    const changes = pulls
        .filter(pull => SHOWN.includes(pull.impact))
        .sort((a, b) => SHOWN.indexOf(a.impact) - SHOWN.indexOf(b.impact) || a.number - b.number)
        .map(pull => {
            const note = extractNote(pull.body);
            return {
                impact: pull.impact,
                number: pull.number,
                title: note?.title || pull.title,
                text: note?.text || [],
                points: note?.points || []
            };
        });
    return {version, date, changes};
}

const baseOf = version => version.replace(/-rc\.\d+$/, '');

// Adds `entry` to the list. A final release absorbs its own candidates, whose
// changes it ships, and preparing the same version again replaces it.
function addRelease(releases, entry) {
    const final = baseOf(entry.version) === entry.version;
    const absorbed = releases.filter(release => release.version === entry.version ||
        (final && baseOf(release.version) === entry.version && release.version !== entry.version));
    const candidates = absorbed.filter(release => release.version !== entry.version);
    const changes = [...candidates.flatMap(release => release.changes), ...entry.changes]
        .sort((a, b) => SHOWN.indexOf(a.impact) - SHOWN.indexOf(b.impact) || a.number - b.number);
    return [{...entry, changes}, ...releases.filter(release => !absorbed.includes(release))];
}

function readReleases(file = DATA_FILE) {
    if (!fs.existsSync(file)) return [];
    const source = fs.readFileSync(file, 'utf8');
    if (!source.startsWith(PREFIX)) throw new Error(`${file} was not written by scripts/whats-new.js`);
    return JSON.parse(source.slice(PREFIX.length).trim().replace(/;$/, ''));
}

function writeReleases(releases, file = DATA_FILE) {
    fs.writeFileSync(file, `${PREFIX}${JSON.stringify(releases, null, 4)};\n`);
}

// Called by release.js prepare: records `version` with the pull requests going out.
function recordRelease(version, pulls, {date = new Date().toISOString().slice(0, 10), file = DATA_FILE} = {}) {
    const releases = addRelease(readReleases(file), releaseEntry(version, date, pulls));
    writeReleases(releases, file);
    return releases[0];
}

module.exports = {DATA_FILE, extractNote, releaseEntry, addRelease, readReleases, writeReleases, recordRelease};
