#!/usr/bin/env node
// Writes the AUR package `fly-browser-bin` for a published release.
//
// The package repackages the release's Linux tarball, so it needs only two
// facts that change: the version, read from `package.json` like everything
// else, and the tarball's checksum, read from the release's SHA256SUMS.txt.
// Nothing here is edited by hand per release; the AUR workflow runs this and
// pushes the result.
//
// The native tarball carries app/fly-browser-native.desktop and app/icons/.
// The package installs that launcher and profile-separated Chromium runtime.
//
// `.SRCINFO` is written here rather than by `makepkg --printsrcinfo` so that
// it can be produced on any runner. The test compares the two where makepkg
// exists.
//
//   node scripts/aur.js --sums SHA256SUMS.txt --out DIR [--tag vX.Y.Z] [--pkgrel N]
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const {declaredVersion, validate, fail} = require('./version-sync');

const PKGNAME = 'fly-browser-bin';
const NAME = 'fly-browser';
const URL = 'https://github.com/Arzuparreta/fly-browser';
const DESCRIPTION = 'A small, minimal browser with full keyboard control and a polished experience for mouse users';
// Runtime libraries of Chromium's Linux build, as packaged in Arch.
const DEPENDS = ['alsa-lib', 'at-spi2-core', 'gtk3', 'libcups', 'libdrm', 'libnotify', 'libsecret', 'libxss', 'libxtst', 'mesa', 'nss', 'xdg-utils'];
const ICON_SIZES = [48, 128, 256];

function tarballName(version) {
    return `Fly-${version}-native-linux-x64.tar.gz`;
}

function checksumFrom(sums, file) {
    for (const line of sums.split('\n')) {
        const match = /^([0-9a-f]{64})\s+\*?(.+)$/.exec(line.trim());
        if (match && match[2] === file) return match[1];
    }
    return fail(`SHA256SUMS.txt has no entry for ${file}`);
}

function checkVersion(version) {
    validate(version);
    // pkgver cannot hold a hyphen, and the AUR follows stable releases only.
    if (version.includes('-')) fail(`${version} is a pre-release; the AUR package follows stable releases only.`);
    return version;
}

function render(version, sha256, pkgrel = 1) {
    checkVersion(version);
    if (!/^[0-9a-f]{64}$/.test(sha256)) fail(`${JSON.stringify(sha256)} is not a SHA-256 checksum`);
    if (!Number.isInteger(pkgrel) || pkgrel < 1) fail(`pkgrel must be a positive integer, not ${JSON.stringify(pkgrel)}`);
    const quoted = list => list.map(item => `'${item}'`).join(' ');
    const source = `${tarballName('${pkgver}')}::\${url}/releases/download/v\${pkgver}/${tarballName('${pkgver}')}`;

    const pkgbuild = `# Maintainer: Arzuparreta <${URL}>
# Generated by scripts/aur.js in ${URL}; change it there.
pkgname=${PKGNAME}
_pkgname=${NAME}
pkgver=${version}
pkgrel=${pkgrel}
pkgdesc='${DESCRIPTION}'
arch=('x86_64')
url='${URL}'
license=('GPL-3.0-or-later')
depends=(${quoted(DEPENDS)})
provides=('${NAME}')
conflicts=('${NAME}')
options=('!strip' '!debug')
source=("${source}")
sha256sums=('${sha256}')

package() {
    cd "fly-browser-native/app"
    install -d "\${pkgdir}/opt/\${_pkgname}"
    cp -a . "\${pkgdir}/opt/\${_pkgname}/"
    # Chromium's sandbox helper, for kernels without unprivileged user namespaces.
    chmod 4755 "\${pkgdir}/opt/\${_pkgname}/chrome-sandbox"

    # Flags in ~/.config/fly-browser-flags.conf (one or more per line, # for
    # comments) are passed to every launch, e.g. --ozone-platform=wayland.
    install -d "\${pkgdir}/usr/bin"
    cat > "\${pkgdir}/usr/bin/\${_pkgname}" <<'EOF'
#!/bin/sh
flags="\${XDG_CONFIG_HOME:-$HOME/.config}/fly-browser-flags.conf"
if [ -r "$flags" ]; then
    # shellcheck disable=SC2046
    set -- $(sed 's/#.*//' "$flags") "$@"
fi
exec /opt/fly-browser/fly-browser-native "$@"
EOF
    chmod 755 "\${pkgdir}/usr/bin/\${_pkgname}"

    sed -e "s|@EXEC@|/usr/bin/fly-browser|" fly-browser-native.desktop > fly-browser.desktop
    install -Dm644 fly-browser.desktop "\${pkgdir}/usr/share/applications/fly-browser-native.desktop"
    for size in ${ICON_SIZES.join(' ')}; do
        install -Dm644 "icons/fly-logo\${size}.png" \\
            "\${pkgdir}/usr/share/icons/hicolor/\${size}x\${size}/apps/fly-browser-native.png"
    done
}
`;

    const fields = [
        ['pkgdesc', DESCRIPTION],
        ['pkgver', version],
        ['pkgrel', pkgrel],
        ['url', URL],
        ['arch', 'x86_64'],
        ['license', 'GPL-3.0-or-later'],
        ...DEPENDS.map(dep => ['depends', dep]),
        ['provides', NAME],
        ['conflicts', NAME],
        ['options', '!strip'],
        ['options', '!debug'],
        ['source', `${tarballName(version)}::${URL}/releases/download/v${version}/${tarballName(version)}`],
        ['sha256sums', sha256]
    ];
    const srcinfo = `pkgbase = ${PKGNAME}\n${fields.map(([key, value]) => `\t${key} = ${value}\n`).join('')}\npkgname = ${PKGNAME}\n`;
    return {PKGBUILD: pkgbuild, '.SRCINFO': srcinfo};
}

function parseOptions(argv) {
    const options = {pkgrel: 1};
    for (let i = 0; i < argv.length; i++) {
        const flag = argv[i];
        if (!['--sums', '--out', '--tag', '--pkgrel'].includes(flag)) fail(`Unknown option ${flag}`);
        const value = argv[++i];
        if (value === undefined) fail(`${flag} needs a value`);
        options[flag.slice(2)] = flag === '--pkgrel' ? Number(value) : value;
    }
    if (!options.sums || !options.out) fail('Usage: node scripts/aur.js --sums SHA256SUMS.txt --out DIR [--tag vX.Y.Z] [--pkgrel N]');
    return options;
}

function main(argv) {
    const options = parseOptions(argv);
    const version = checkVersion(declaredVersion());
    if (options.tag && options.tag !== `v${version}`) fail(`${options.tag} was requested, but the tree declares v${version}.`);
    const sha256 = checksumFrom(fs.readFileSync(options.sums, 'utf8'), tarballName(version));
    fs.mkdirSync(options.out, {recursive: true});
    for (const [file, content] of Object.entries(render(version, sha256, options.pkgrel))) {
        fs.writeFileSync(path.join(options.out, file), content);
    }
    console.log(`${PKGNAME} ${version}-${options.pkgrel} written to ${options.out}`);
}

if (require.main === module) {
    try {
        main(process.argv.slice(2));
    } catch (error) {
        if (!error.releaseTooling) throw error;
        console.error(error.message);
        process.exit(1);
    }
}

module.exports = {PKGNAME, ICON_SIZES, render, checksumFrom, tarballName, parseOptions};
