const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const {createBookmarkStore} = require('../bookmarkStore');
const {createFrequentSites} = require('../frequentSites');
const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'fly-bookmark-store-'));
const originalRead = fs.readFileSync;
try {
    const file = path.join(directory, 'bookmarks.json');
    fs.writeFileSync(file, JSON.stringify([{url:'https://saved.test/page', title:'Saved'}]));
    let reads = 0;
    fs.readFileSync = function (target, ...args) { if (target === file) reads++; return originalRead(target, ...args); };
    let events = 0;
    const store = createBookmarkStore(file, () => events++);
    const history = Array.from({length:7}, (_, i) => ({url:`https://${i ? 'site'+i : 'saved'}.test/path`, timestamp:Date.now()}));
    const sites = createFrequentSites(path.join(directory, 'hidden.json'), () => history, Date.now, () => store.origins());
    assert(store.origins().has('https://saved.test'));
    assert.equal(sites.get().length, 5, 'Excluded entries are replaced before taking the top five');
    assert(!sites.get().some(site => site.url === 'https://saved.test'));
    store.read(); store.origins(); sites.get();
    assert.equal(reads, 1, 'Repeated reads use memory');
    const before = sites.get();
    const origins = store.origins();
    assert(store.save([{url:'https://saved.test/another-path', title:'Renamed'}, {url:'invalid'}, null]));
    assert.equal(store.origins(), origins, 'Changing paths or titles preserves the origin set');
    assert.equal(sites.get(), before, 'Unchanged origins preserve the ranking cache');
    assert(store.save([{url:'https://site1.test', title:'One'}, {url:'https://site2.test/page', title:'Two'}]));
    assert(!sites.get().some(site => ['https://site1.test', 'https://site2.test'].includes(site.url)));
    assert(sites.get().some(site => site.url === 'https://saved.test'), 'Removing a bookmark makes the origin eligible again');
    assert.equal(reads, 1, 'Saves do not reread the file');
    assert.equal(events, 2);
    fs.mkdirSync(file + '.tmp');
    const last = store.read();
    assert.equal(store.save([]), false);
    assert.equal(store.read(), last, 'Failed writes preserve memory and exclusions');
    assert.equal(events, 2, 'Failed writes do not broadcast a change');
    assert.equal(store.save({}), false);
    const restarted = createBookmarkStore(file);
    assert(restarted.origins().has('https://site1.test'));
    assert.equal(history.length, 7, 'History is preserved');
    const separateOrigins = [{url:'https://site1.test/path'}, {url:'http://site1.test'}, {url:'https://sub.site1.test'}, {url:'https://site1.test:8443'}];
    const distinct = createFrequentSites(path.join(directory, 'other-hidden.json'), () => separateOrigins, Date.now, () => restarted.origins());
    assert.deepEqual(new Set(distinct.get().map(site => site.url)), new Set(['http://site1.test', 'https://sub.site1.test', 'https://site1.test:8443']));

    console.log('Bookmark store: one disk read, reactive origin exclusions, unchanged cache, top-five refill, failed saves and restart pass.');
} finally {
    fs.readFileSync = originalRead;
    fs.rmSync(directory, {recursive:true, force:true});
}
