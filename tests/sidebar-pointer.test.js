const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const context = vm.createContext({performance: {timeOrigin: 1000}});
vm.runInContext(fs.readFileSync(require.resolve('../modules/sidebarPointer.js'), 'utf8').replace(/export /g, ''), context);
assert(context.isCurrentGuestPointerEntry(1005));
context.recordSidebarPointerEntry({timeStamp: 20});
assert.equal(context.isCurrentGuestPointerEntry(1010), false, 'Delayed guest entry cannot close a newer host hover');
assert(context.isCurrentGuestPointerEntry(1020), 'Same-time entry is accepted');
assert(context.isCurrentGuestPointerEntry(1030), 'New entry closes the sidebar even if host :hover remains stale');
context.recordSidebarPointerEntry({timeStamp: 50});
assert.equal(context.isCurrentGuestPointerEntry(1030), false, 'Returning to host invalidates queued guest entry');
for (const invalid of [undefined, null, NaN, Infinity, '1050']) assert.equal(context.isCurrentGuestPointerEntry(invalid), false);
console.log('Sidebar pointer ordering rejects stale guest IPC and accepts current entry.');
