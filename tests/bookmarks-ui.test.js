const {_electron} = require(process.env.FLY_PLAYWRIGHT_MODULE || 'playwright');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const http = require('node:http');
const assert = require('node:assert/strict');
const createFixture = require('./electron-fixture');
const root = path.resolve(__dirname, '..');
(async () => {
    const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'fly-bookmarks-'));
    const server = http.createServer((_req, res) => res.end('<!doctype html><title>Bookmark fixture</title><input id="editable" style="margin:100px">'));
    await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
    const base = `http://127.0.0.1:${server.address().port}`;
    const configDir = path.join(directory, '.config/fly-browser');
    fs.mkdirSync(configDir, {recursive:true});
    fs.writeFileSync(path.join(configDir, 'bookmarks.json'), JSON.stringify([
        {title:'Alpha', url:base + '/alpha'}, {title:'Beta', url:base + '/beta'}
    ]));
    const oldFile = path.join(configDir, 'quickmarks.json');
    const oldData = JSON.stringify({g:{title:'Old shortcut', url:base + '/old'}});
    fs.writeFileSync(oldFile, oldData);
    fs.writeFileSync(path.join(configDir, 'keybinds.json'), JSON.stringify({version:2, changesOnly:true,
        shortcuts:{'set-quickmark':['Ctrl+Shift+Q'], 'jump-quickmark':['Ctrl+J']}, normal:{}}));
    let app;
    try {
        app = await _electron.launch({executablePath:path.join(root, 'node_modules/electron/dist/electron'), args:['--no-sandbox','--disable-gpu','--ozone-platform=x11',createFixture(root, directory)]});
        const page = await app.firstWindow();
        page.setDefaultTimeout(15000);
        const errors = [];
        page.on('pageerror', error => errors.push(error.message));
        await page.waitForFunction(() => !!window.executeBrowserAction && document.getElementById('KeyboardStatus').textContent === 'All changes saved');
        await page.waitForFunction(() => {try {return !document.querySelector('webview').isLoading();} catch {return false;}});
        assert.equal(await page.evaluate(() => typeof window.flyAPI.readQuickmarks), 'undefined');
        assert.equal(await page.locator('#QuickmarksResultsList').count(), 0);
        await page.keyboard.press('Control+Shift+b');
        await page.locator('#BookmarksOverlay').waitFor({state:'visible'});
        assert.equal(await page.locator('.bookmarks-list-pane').count(), 1);
        assert.equal(await page.locator('#BookmarksResultsList .bookmark-item-row').count(), 2);
        await page.keyboard.press('ArrowDown');
        assert.match(await page.locator('#BookmarksResultsList .selected').textContent(), /Beta/);
        await page.keyboard.press('ArrowUp');
        assert.match(await page.locator('#BookmarksResultsList .selected').textContent(), /Alpha/);
        await page.locator('#BookmarkSearchInput').fill('Beta');
        assert.equal(await page.locator('#BookmarksResultsList .bookmark-item-row').count(), 1);
        await page.keyboard.press('Enter');
        await page.locator('#BookmarksOverlay').waitFor({state:'hidden'});
        await page.waitForFunction(() => [...document.querySelectorAll('webview')].some(view => view.getClientRects().length && view.getURL().endsWith('/beta')));
        const view = () => page.locator('webview:visible');
        await view().click({position:{x:120, y:110}});
        await page.evaluate(() => [...document.querySelectorAll('webview')].find(view => view.getClientRects().length).executeJavaScript('document.getElementById("editable").focus()'));
        await page.keyboard.press('Control+j');
        await page.keyboard.press('Control+Shift+q');
        await page.keyboard.type('plain typing');
        assert.equal(await page.evaluate(() => [...document.querySelectorAll('webview')].find(view => view.getClientRects().length).executeJavaScript('document.getElementById("editable").value')), 'plain typing');
        await page.evaluate(url => [...document.querySelectorAll('webview')].find(view => view.getClientRects().length).loadURL(url), base + '/gamma');
        await page.keyboard.press('Control+d');
        await page.waitForFunction(async () => (await window.flyAPI.readBookmarks()).some(item => item.url.endsWith('/gamma')));
        await page.keyboard.press('Control+Shift+b');
        await page.locator('#BookmarksOverlay').waitFor({state:'visible'});
        await page.locator('#BookmarkSearchInput').fill('Alpha');
        await page.keyboard.press('Delete');
        assert.equal(await page.locator('#BookmarksResultsList .bookmark-item-row').count(), 0);
        assert(!(await page.evaluate(() => window.flyAPI.readBookmarks())).some(item => item.title === 'Alpha'));
        await page.locator('#BookmarkSearchInput').fill('Beta');
        await page.locator('#BookmarksResultsList .bookmark-delete-btn').click();
        await page.waitForFunction(async () => (await window.flyAPI.readBookmarks()).length === 1);
        await page.keyboard.press('Escape');
        await page.keyboard.press('Control+p');
        await page.locator('#PaletteInput').fill('quickmark');
        assert.match(await page.locator('#PaletteList .palette-item-title').textContent(), /Run in terminal/);
        assert.equal(await page.evaluate(async () => Object.keys((await import('./modules/overlays/commandPalette.js')).commandRegistry).some(id => id.includes('quickmark'))), false);
        assert.equal(fs.readFileSync(oldFile, 'utf8'), oldData, 'Unused legacy data is not touched');
        assert.deepEqual(errors, []);
        console.log('Bookmarks Electron: single list, keyboard navigation, filtering, open/delete, retired shortcuts and editable-page typing pass.');
    } finally {
        if (app) await app.close();
        await new Promise(resolve => server.close(resolve));
        fs.rmSync(directory, {recursive:true, force:true});
    }
})().catch(error => {console.error(error); process.exitCode=1;});
