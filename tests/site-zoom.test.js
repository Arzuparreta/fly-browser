const assert = require('node:assert/strict');
const { EventEmitter } = require('node:events');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { createSiteZoom, hostname } = require('../siteZoom');
const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'fly-zoom-'));
const file = path.join(directory, 'zoom.json');
function guest(store, url, privateSession = false) {
    const view = new EventEmitter();
    Object.assign(view, { privateSession, url, level: 0, getURL() { return this.url; }, getZoomLevel() { return this.level; }, setZoomLevel(level) { this.level = level; }, setZoomMode() {}, isDestroyed() { return false; } });
    store.attach(view);
    view.emit('did-navigate');
    return view;
}
try {
    const store = createSiteZoom(file);
    const first = guest(store, 'https://example.com/a');
    const second = guest(store, 'http://example.com:8080/b');
    const subdomain = guest(store, 'https://sub.example.com/');
    store.change(first, 'zoom-in');
    assert.equal(first.level, 0.5);
    assert.equal(second.level, 0.5);
    assert.equal(subdomain.level, 0);
    assert.equal(guest(createSiteZoom(file), 'https://example.com/c').level, 0.5);
    first.url = 'https://other.example/'; first.emit('did-navigate');
    assert.equal(first.level, 0);
    first.url = 'https://example.com/back'; first.emit('did-navigate');
    assert.equal(first.level, 0.5);
    first.emit('zoom-changed', {}, 'in');
    assert.equal(second.level, 1);
    store.change(first, 'reset-zoom');
    assert.equal(second.level, 0);
    assert.deepEqual(JSON.parse(fs.readFileSync(file)), {});
    for (let i = 0; i < 30; i++) store.change(first, 'zoom-out');
    assert.equal(first.level, -5);
    assert.equal(hostname('file:///tmp/private.html'), '');
    assert.equal(hostname('https://EXAMPLE.COM:123/path'), 'example.com');
    const isolated = createSiteZoom(file, { isPrivate: view => view.privateSession });
    const normal = guest(isolated, 'https://example.com');
    const privateTab = guest(isolated, 'https://example.com', true);
    const privatePeer = guest(isolated, 'http://example.com:8080', true);
    assert.equal(privateTab.level, 0, 'Private tabs must not inherit saved preferences');
    const saved = fs.readFileSync(file, 'utf8');
    privateTab.emit('zoom-changed', {}, 'in');
    assert.equal(privatePeer.level, 0.5);
    assert.equal(normal.level, -5);
    assert.equal(fs.readFileSync(file, 'utf8'), saved);
    isolated.change(normal, 'reset-zoom');
    assert.equal(privateTab.level, 0.5, 'Normal reset must not affect private tabs');
    const afterReset = fs.readFileSync(file, 'utf8');
    isolated.change(privateTab, 'reset-zoom');
    assert.equal(privatePeer.level, 0);
    assert.equal(fs.readFileSync(file, 'utf8'), afterReset);
    privateTab.url = 'https://private-only.example'; privateTab.emit('did-navigate');
    isolated.change(privateTab, 'zoom-in');
    privateTab.url = 'https://elsewhere.example'; privateTab.emit('did-navigate');
    privateTab.url = 'https://private-only.example'; privateTab.emit('did-navigate');
    assert.equal(privateTab.level, 0.5);
    assert.equal(fs.readFileSync(file, 'utf8'), afterReset, 'Private-only hosts must never reach disk');
    const restarted = createSiteZoom(file, { isPrivate: view => view.privateSession });
    assert.equal(guest(restarted, 'https://private-only.example', true).level, 0);
    const absentFile = path.join(directory, 'private-only', 'zoom.json');
    const privateOnly = createSiteZoom(absentFile, { isPrivate: () => true });
    privateOnly.change(guest(privateOnly, 'https://secret.example'), 'zoom-in');
    assert.equal(fs.existsSync(path.dirname(absentFile)), false, 'Private zoom must not create files or directories');
    fs.writeFileSync(file, '{');
    assert.equal(guest(createSiteZoom(file), 'https://example.com').level, 0);
    console.log('Site zoom tests passed');
} finally { fs.rmSync(directory, { recursive: true, force: true }); }
